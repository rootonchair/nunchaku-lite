"""Write the Hub build's copy of the shared Metal kernels: ``nunchaku_lite_kernels_metal/lite_shaders.hpp``.

The q/k norm + RoPE library (``nunchaku_lite/shaders.py``) and the vendored MLX attention kernel
(``nunchaku_lite/ops/_mlx_steel_attention.py``) are the single sources of truth. ``nunchaku_lite`` compiles them
with ``torch.mps.compile_shader`` only when the installed Hub build predates them; the Hub build compiles this
header. Run after changing either source (``tests/test_hub_shaders_in_sync.py`` fails until you do):

    python tools/sync_hub_shaders.py
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "nunchaku-lite-kernels/nunchaku_lite_kernels_metal/lite_shaders.hpp"


def _load(name: str, path: Path):
    # Load by path: importing the nunchaku_lite package would import torch.
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def render() -> str:
    shaders = _load("_lite_shaders", ROOT / "src/nunchaku_lite/shaders.py")
    attention = _load("_lite_attention", ROOT / "src/nunchaku_lite/ops/_mlx_steel_attention.py")
    # MLX's license notice (the comment block of the vendored module) goes inside the attention source string,
    # which the compiled library embeds.
    header = (ROOT / "src/nunchaku_lite/ops/_mlx_steel_attention.py").read_text().split("MLX_VERSION =")[0]
    notice = "\n".join("//" + line[1:] for line in header.splitlines() if line.startswith("#"))
    sources = {
        "kQkNormRopeLiteSource": shaders.qk_norm_rope_library_source(constant_args=True),
        # MLX's function constants (align_Q, align_K, has_mask, ...) stay; svdq_metal.mm specializes them.
        "kAttentionNaxSource": f"{notice}\n{attention.SOURCE}{shaders.attention_instantiations()}",
    }
    out = [
        "#pragma once",
        "",
        "// Generated by tools/sync_hub_shaders.py; do not edit. Sources: src/nunchaku_lite/shaders.py (q/k norm +",
        f"// RoPE) and src/nunchaku_lite/ops/_mlx_steel_attention.py (MLX {attention.MLX_VERSION} Neural Accelerator",
        "// flash attention, MIT license: see kAttentionNaxSource). Compiled at runtime (first use) by svdq_metal.mm.",
        "namespace nunchaku_lite::metal {",
        "",
    ]
    for name, source in sources.items():
        if ')METAL"' in source:
            raise RuntimeError(f"{name} contains the raw-string delimiter.")
        out += [f'static const char* {name} = R"METAL({source})METAL";', ""]
    out += ["}  // namespace nunchaku_lite::metal", ""]
    return "\n".join(out)


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KiB)")


if __name__ == "__main__":
    main()
