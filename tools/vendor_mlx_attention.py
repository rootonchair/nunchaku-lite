"""Regenerate ``src/nunchaku_lite/ops/_mlx_steel_attention.py`` from an installed MLX.

The PyTorch MPS attention kernel is MLX's Neural Accelerator ("NAX") flash attention, compiled at runtime with
``torch.mps.compile_shader``. This script inlines the kernel header and everything it includes (each header once)
into a single Metal source and writes it, with MLX's MIT license notice, as a Python module.

    python tools/vendor_mlx_attention.py            # needs `pip install mlx`
    python tools/sync_hub_shaders.py                # then refresh the Hub build's copy
"""

from __future__ import annotations

import re
from importlib import metadata
from pathlib import Path

import mlx

KERNEL = "mlx/backend/metal/kernels/steel/attn/kernels/steel_attention_nax.h"
ENTRY_POINTS = ("mlx/backend/metal/kernels/utils.h", KERNEL)
OUT = Path(__file__).resolve().parents[1] / "src/nunchaku_lite/ops/_mlx_steel_attention.py"


def _flatten(root: Path) -> str:
    seen: set[Path] = set()

    def inline(path: Path) -> list[str]:
        if path in seen:
            return []
        seen.add(path)
        lines: list[str] = []
        for line in path.read_text().splitlines():
            match = re.match(r'\s*#include\s+"(mlx/[^"]+)"', line)
            if match:
                lines += inline(root / match.group(1))
            elif line.strip() != "#pragma once":
                lines.append(line.rstrip())
        return lines

    return "\n".join(line for entry in ENTRY_POINTS for line in inline(root / entry)) + "\n"


def main() -> None:
    root = Path(mlx.__path__[0]) / "include"
    source = _flatten(root)
    if '"""' in source:
        raise RuntimeError("Flattened source contains a triple quote; cannot embed it in a raw string.")
    dist = metadata.distribution("mlx")
    license_text = next(f for f in dist.files if f.name == "LICENSE").read_text().strip()
    notice = "\n".join(f"# {line}".rstrip() for line in license_text.splitlines())
    OUT.write_text(
        f'"""MLX {dist.version} Neural Accelerator flash attention, flattened into one Metal source.\n\n'
        f"Source: ``{KERNEL}`` and its includes.\nGenerated by ``tools/vendor_mlx_attention.py``; do not edit. Compiled at runtime by\n"
        ":mod:`nunchaku_lite.ops.mps` with ``torch.mps.compile_shader``.\n"
        '"""\n\n'
        f"# Vendored from MLX (https://github.com/ml-explore/mlx) under the MIT license:\n#\n{notice}\n\n"
        f'MLX_VERSION = "{dist.version}"\n\n'
        f'SOURCE = r"""{source}"""\n'
    )
    print(f"wrote {OUT} ({len(source.splitlines())} lines, MLX {dist.version}); now run tools/sync_hub_shaders.py")


if __name__ == "__main__":
    main()
